create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null,
  service_name text not null,
  service_price numeric(10, 2) not null check (service_price >= 0),
  deposit_amount numeric(10, 2) not null check (deposit_amount >= 0),
  balance_amount numeric(10, 2) not null check (balance_amount >= 0),
  appointment_date date not null,
  appointment_time time not null,
  payment_method text not null check (payment_method in ('card', 'paypal')),
  tattoo_notes text,
  ticket_number text not null unique,
  booking_status text not null default 'pending'
    check (booking_status in ('pending', 'confirmed', 'attended')),
  payment_status text not null default 'unpaid'
    check (payment_status in ('unpaid', 'paid')),
  created_at timestamptz not null default now()
);

create index if not exists bookings_created_at_idx
  on public.bookings (created_at desc);

create table if not exists public.visitor_questions (
  id bigint generated by default as identity primary key,
  customer_name text,
  customer_email text not null,
  question_text text not null,
  created_at timestamptz not null default now()
);

create index if not exists visitor_questions_created_at_idx
  on public.visitor_questions (created_at desc);

alter table public.bookings enable row level security;
alter table public.visitor_questions enable row level security;
